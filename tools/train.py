#!/usr/bin/env python3
"""Deterministic CPU training and symmetric int8 export of a character MLP."""
import argparse, json, pathlib, hashlib
import numpy as np
ROOT=pathlib.Path(__file__).resolve().parents[1]
VOCAB='\n abcdefghijklmnopqrstuvwxyz.'
CTX, EMB, HID=16,4,48
def data(corpus):
    xs=[]; ys=[]
    for line in corpus.splitlines():
        ctx=[0]*CTX
        for ch in line+'\n':
            y=VOCAB.index(ch); xs.append(ctx[:]); ys.append(y); ctx=ctx[1:]+[y]
    return np.array(xs),np.array(ys)
def quant(a):
    s=float(np.max(np.abs(a)))/127 or 1
    return np.rint(a/s).clip(-127,127).astype(np.int8),s

def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--steps',type=int,default=1800); ap.add_argument('--corpus',type=pathlib.Path,default=ROOT/'corpus.txt'); args=ap.parse_args()
    corpus=args.corpus.read_text(); assert all(c in VOCAB for c in corpus), 'Corpus must use model vocabulary'
    assert args.steps>0 and corpus.strip(), 'Positive steps and nonempty corpus required'
    rng=np.random.default_rng(20261007); x,y=data(corpus); n=len(y); v=len(VOCAB)
    p=[rng.normal(0,.2,(v,EMB)),rng.normal(0,.1,(CTX*EMB,HID)),np.zeros(HID),rng.normal(0,.1,(HID,v)),np.zeros(v)]
    m=[np.zeros_like(a) for a in p]; u=[np.zeros_like(a) for a in p]
    for step in range(1,args.steps+1):
        inp=p[0][x].reshape(n,-1); pre=inp@p[1]+p[2]; h=np.maximum(pre,0); z=h@p[3]+p[4]
        prob=np.exp(z-z.max(1,keepdims=True)); prob/=prob.sum(1,keepdims=True)
        loss=-np.log(prob[np.arange(n),y]+1e-20).mean()
        dz=prob.copy(); dz[np.arange(n),y]-=1; dz/=n
        dh=(dz@p[3].T)*(pre>0); de=(dh@p[1].T).reshape(n,CTX,EMB)
        ge=np.zeros_like(p[0]); np.add.at(ge,x.ravel(),de.reshape(-1,EMB))
        g=[ge,inp.T@dh,dh.sum(0),h.T@dz,dz.sum(0)]
        for j in range(5):
            m[j]=.9*m[j]+.1*g[j]; u[j]=.999*u[j]+.001*g[j]**2
            p[j]-=.015*(m[j]/(1-.9**step))/(np.sqrt(u[j]/(1-.999**step))+1e-8)
        if step%300==0: print(f'step={step} loss={loss:.6f}',flush=True)
    inp=p[0][x].reshape(n,-1); z=np.maximum(inp@p[1]+p[2],0)@p[3]+p[4]
    prob=np.exp(z-z.max(1,keepdims=True)); prob/=prob.sum(1,keepdims=True)
    loss=-np.log(prob[np.arange(n),y]+1e-20).mean()
    e,se=quant(p[0]); w,sw=quant(p[1]); o,so=quant(p[3]); b=p[2].astype(np.float32); c=p[4].astype(np.float32)
    np.savez(ROOT/'model.npz',e=e,w=w,o=o,b=b,c=c,se=np.float32(se),sw=np.float32(sw),so=np.float32(so))
    def arr(name,a,typ):
        vals=','.join(str(int(q)) if typ=='int8_t' else f'{float(q):.9e}f' for q in a.ravel())
        return f'static const {typ} {name}[{a.size}] MODEL_STORAGE = {{{vals}}};\n'
    out='#pragma once\n// Generated by tools/train.py; do not hand edit.\n'
    out+=f'static const int MODEL_CONTEXT={CTX}, MODEL_EMBED={EMB}, MODEL_HIDDEN={HID}, MODEL_VOCAB={v};\n'
    out+=f'static const float MODEL_SE={se:.9e}f, MODEL_SW={sw:.9e}f, MODEL_SO={so:.9e}f;\n'
    for name,a,t in [('MODEL_E',e,'int8_t'),('MODEL_W',w,'int8_t'),('MODEL_O',o,'int8_t'),('MODEL_B',b,'float'),('MODEL_C',c,'float')]:out+=arr(name,a,t)
    (ROOT/'tiny_uno/model_weights.h').write_text(out)
    meta=dict(seed=20261007,steps=args.steps,training_characters=n,loss=float(loss),training_accuracy=float((z.argmax(1)==y).mean()),context=CTX,embedding=EMB,hidden=HID,vocabulary=VOCAB,weight_bytes=int(e.size+w.size+o.size+4*(b.size+c.size)),corpus_sha256=hashlib.sha256(corpus.encode()).hexdigest(),architecture='embedding + flattened context + ReLU hidden + linear logits; greedy decoding')
    (ROOT/'model_metadata.json').write_text(json.dumps(meta,indent=2)+'\n')
if __name__=='__main__':main()
